import fs from 'node:fs/promises'
import path from 'node:path'
import { seoRoutes } from '../src/config/seoRoutes.js'

const canonicalRedirects = seoRoutes
  .filter((route) => route.path !== '/' && route.path.endsWith('/'))
  .map((route) => `${route.path.slice(0, -1)} ${route.path} 301`)

const retiredRedirects = [
  ['/invisalign/', '/orthodontie-invisible-sete/'],
  ['/orthodontie-invisible-meze/', '/invisalign-bassin-de-thau/'],
  ['/invisalign-frontignan/', '/invisalign-bassin-de-thau/'],
  ['/invisalign-marseillan/', '/invisalign-bassin-de-thau/'],
  ['/orthodontie-invisible-agde/', '/invisalign-bassin-de-thau/'],
  ['/orthodontie-adulte-balaruc-les-bains/', '/invisalign-bassin-de-thau/'],
  ['/blog/prix-orthodontie-invisible-sete/', '/prix-orthodontie-invisible-sete/'],
  ['/blog/aligner-dents-avant-pose-implant/', '/blog/aligner-dents-avant-implant/'],
  ['/blog/orthodontie-sete-quand-consulter-alignement-dentaire/', '/orthodontie-sete/'],
  ['/blog/orthodontie-invisible-sete-questions-avant-bilan/', '/orthodontie-invisible-sete/'],
  ['/blog/verite-invisalign-taquets-temps-port-gene/', '/blog/orthodontie-invisible-quotidien-repas-entretien-parole/'],
  ['/blog/orthodontie-bassin-de-thau-suivi-sete/', '/invisalign-bassin-de-thau/'],
].flatMap(([from, to]) => [
  `${from.slice(0, -1)} ${to} 301`,
  `${from} ${to} 301`,
])

const redirects = [
  '/actualities /blog/ 301',
  '/actualities/ /blog/ 301',
  '/actualites /blog/ 301',
  '/actualites/ /blog/ 301',
  ...retiredRedirects,
  ...canonicalRedirects,
  // Use the clean directory URL: Pages normalizes /index.html before serving.
  // Keep the original article ID in the browser for React Router.
  '/actualities/* /legacy-actuality/ 200',
  '/actualites/* /blog/ 301',
]

const unique = [...new Set(redirects)]
await fs.writeFile(path.resolve('public/_redirects'), `${unique.join('\n')}\n`)

// Generate the same legacy mappings for alternate hosts. Actual files are served
// directly and unmatched paths retain a 404 instead of returning the homepage.
const rules = unique.map((line) => {
  const [from, to, status] = line.split(' ')
  return { from, to, status: Number(status) }
})
const vercel = JSON.parse(await fs.readFile('vercel.json', 'utf8'))
vercel.trailingSlash = true
vercel.redirects = rules.filter((rule) => rule.status === 301 && !canonicalRedirects.includes(`${rule.from} ${rule.to} 301`))
  .map((rule) => ({ source: rule.from.replace('*', ':path*'), destination: rule.to, permanent: true }))
vercel.rewrites = [{ source: '/actualities/:path+', destination: '/legacy-actuality/index.html' }]
await fs.writeFile('vercel.json', `${JSON.stringify(vercel, null, 2)}\n`)

const regexEscape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const apache = rules.filter((rule) => rule.status === 301 && !rule.from.includes('*'))
  .map((rule) => `  RewriteRule ^${regexEscape(rule.from.slice(1))}$ ${rule.to} [R=301,L,NE]`)
await fs.writeFile('public/.htaccess', `# Generated by scripts/generate-redirects.mjs.\nErrorDocument 404 /404.html\n<IfModule mod_rewrite.c>\n  RewriteEngine On\n  RewriteBase /\n${apache.join('\n')}\n  RewriteRule ^actualities/.+ /legacy-actuality/index.html [L]\n  RewriteRule ^actualites/.+ /blog/ [R=301,L]\n</IfModule>\n`)
console.log(`Updated redirects with ${unique.length} rules`)
